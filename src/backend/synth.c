/* ============================================================== scripts */

const char *syn_script_name(BkTool tool)
{
    switch (tool) {
    case BK_TOOL_VIVADO: return "synth.tcl";
    case BK_TOOL_QUARTUS: return "synth_quartus.tcl";
    default: break;
    }
    return "synth.ys";
}

void syn_command(BkTool tool, StrBuf *out)
{
    switch (tool) {
    case BK_TOOL_VIVADO: sb_puts(out, "vivado -mode batch -nojournal -nolog -source synth.tcl"); break;
    case BK_TOOL_QUARTUS: sb_puts(out, "quartus_sh -t synth_quartus.tcl"); break;
    default: sb_puts(out, "yosys -q -l synth.log -s synth.ys"); break;
    }
}

static int syn_istarts(const char *s, const char *p)
{
    while (*p) {
        if (tern_to_lower((unsigned char)*s) != tern_to_lower((unsigned char)*p))
            return 0;
        s++;
        p++;
    }
    return 1;
}

/* Quartus FAMILY for a device name */
static const char *syn_intel_family(const char *dev)
{
    if (!dev)
        return "Cyclone V";
    if (syn_istarts(dev, "5ce") || syn_istarts(dev, "5cg") || syn_istarts(dev, "5cs"))
        return "Cyclone V";
    if (syn_istarts(dev, "10m"))
        return "MAX 10";
    if (syn_istarts(dev, "ep4cgx"))
        return "Cyclone IV GX";
    if (syn_istarts(dev, "ep4ce"))
        return "Cyclone IV E";
    if (syn_istarts(dev, "10cl"))
        return "Cyclone 10 LP";
    if (syn_istarts(dev, "10cx"))
        return "Cyclone 10 GX";
    if (syn_istarts(dev, "5sg"))
        return "Stratix V";
    if (syn_istarts(dev, "5a"))
        return "Arria V";
    if (syn_istarts(dev, "10a"))
        return "Arria 10";
    if (syn_istarts(dev, "1s"))
        return "Stratix 10";
    if (syn_istarts(dev, "ag"))
        return "Agilex 7";
    return "Cyclone V";
}

/* synth_xilinx -family */
static const char *syn_xilinx_family(const char *dev)
{
    if (!dev)
        return "xc7";
    if (syn_istarts(dev, "xc6s"))
        return "xc6s";
    if (syn_istarts(dev, "xcku") || syn_istarts(dev, "xcvu") || syn_istarts(dev, "xczu") || syn_istarts(dev, "xcau"))
        return (strchr(dev, 'p') || strchr(dev, 'P') || syn_istarts(dev, "xczu") || syn_istarts(dev, "xcau")) ? "xcup"
                                                                                                             : "xcu";
    return "xc7";
}

void syn_script(const SynScriptIn *in, StrBuf *out)
{
    size_t i;
    const char *dir = in->src_dir && *in->src_dir ? in->src_dir : ".";
    const char *part = in->part ? in->part : in->device;
    switch (in->tool) {
    case BK_TOOL_VIVADO:
        sb_printf(out, "# synth.tcl: generated by tern synth for %s. Do not edit.\n", in->top);
        sb_puts(out, "# run: vivado -mode batch -nojournal -nolog -source synth.tcl\n");
        if (!part) {
            sb_puts(out, "# no device in the build target: set `device` (or `part`) in [target.<name>]\n");
            part = "xc7a35tcpg236-1";
        }
        sb_printf(out, "set_part %s\n", part);
        sb_printf(out, "read_verilog%s {", in->sv ? " -sv" : "");
        for (i = 0; i < in->nfiles; i++)
            sb_printf(out, " %s/%s", dir, in->files[i]);
        sb_puts(out, " }\n");
        if (in->xdc)
            sb_printf(out, "read_xdc %s/%s\n", dir, in->xdc);
        sb_printf(out, "synth_design -top %s -part %s\n", in->top, part);
        sb_puts(out, "opt_design\nplace_design\nroute_design\n"
                     "report_utilization -file utilization.rpt\n"
                     "report_timing_summary -file timing.rpt\n");
        sb_printf(out, "write_checkpoint -force %s_routed.dcp\n", in->top);
        return;
    case BK_TOOL_QUARTUS:
        sb_printf(out, "# synth_quartus.tcl: generated by tern synth for %s. Do not edit.\n", in->top);
        sb_puts(out, "# run: quartus_sh -t synth_quartus.tcl\n");
        sb_puts(out, "load_package flow\n");
        sb_printf(out, "project_new %s -overwrite\n", in->top);
        sb_printf(out, "set_global_assignment -name FAMILY \"%s\"\n",
                  in->family_name ? in->family_name : syn_intel_family(in->device));
        if (in->device)
            sb_printf(out, "set_global_assignment -name DEVICE %s\n", in->device);
        sb_printf(out, "set_global_assignment -name TOP_LEVEL_ENTITY %s\n", in->top);
        sb_puts(out, "set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files\n");
        for (i = 0; i < in->nfiles; i++)
            sb_printf(out, "set_global_assignment -name %s %s/%s\n", in->sv ? "SYSTEMVERILOG_FILE" : "VERILOG_FILE",
                      dir, in->files[i]);
        if (in->sdc)
            sb_printf(out, "set_global_assignment -name SDC_FILE %s/%s\n", dir, in->sdc);
        sb_puts(out, "execute_flow -compile\nproject_close\n");
        return;
    default: break;
    }
    sb_printf(out, "# synth.ys: generated by tern synth for %s (%s). Do not edit.\n", in->top,
              bk_family_name(in->family));
    sb_puts(out, "# run: yosys -q -l synth.log -s synth.ys\n");
    sb_printf(out, "read_verilog -DSYNTHESIS%s", in->sv ? " -sv" : "");
    for (i = 0; i < in->nfiles; i++)
        sb_printf(out, " %s%s%s", strcmp(dir, ".") == 0 ? "" : dir, strcmp(dir, ".") == 0 ? "" : "/", in->files[i]);
    sb_putc(out, '\n');
    sb_printf(out, "hierarchy -check -top %s\n", in->top);
    switch (in->family) {
    case BK_FAM_ICE40: sb_printf(out, "synth_ice40 -top %s -json %s.json\n", in->top, in->top); break;
    case BK_FAM_ECP5: sb_printf(out, "synth_ecp5 -top %s -json %s.json\n", in->top, in->top); break;
    case BK_FAM_GOWIN: sb_printf(out, "synth_gowin -top %s -json %s.json\n", in->top, in->top); break;
    case BK_FAM_XILINX:
        sb_printf(out, "synth_xilinx -top %s -family %s -flatten -edif %s.edif\n", in->top,
                  syn_xilinx_family(in->device), in->top);
        break;
    case BK_FAM_INTEL: sb_printf(out, "synth_intel_alm -top %s\n", in->top); break;
    default: sb_printf(out, "synth -top %s -flatten\n", in->top); break;
    }
    sb_puts(out, "tee -o utilization.txt stat\n");
}

/* ============================================================== parsers */

void syn_report_init(SynReport *r)
{
    r->luts = r->ffs = r->brams = r->dsps = r->cells = -1;
    r->fmax_mhz = -1;
    r->wns_ns = 0;
    r->has_wns = 0;
    r->period_ns = -1;
}

static const char *syn_skip_ws(const char *p)
{
    while (*p == ' ' || *p == '\t')
        p++;
    return p;
}

/* parses an integer with optional `,` thousands separators */
static int syn_int(const char *p, int64_t *out, const char **end)
{
    int64_t v = 0;
    int any = 0;
    p = syn_skip_ws(p);
    while (tern_is_digit((unsigned char)*p) || (*p == ',' && any && tern_is_digit((unsigned char)p[1]))) {
        if (*p != ',') {
            v = v * 10 + (*p - '0');
            any = 1;
        }
        p++;
    }
    if (end)
        *end = p;
    if (any)
        *out = v;
    return any;
}

static int syn_num(const char *p, double *out, const char **end)
{
    char *e;
    double v;
    p = syn_skip_ws(p);
    if (!(tern_is_digit((unsigned char)*p) || ((*p == '-' || *p == '+' || *p == '.') && (tern_is_digit((unsigned char)p[1]) || p[1] == '.'))))
        return 0;
    v = strtod(p, &e);
    if (e == p)
        return 0;
    *out = v;
    if (end)
        *end = e;
    return 1;
}

typedef enum SynCellClass { SYN_C_OTHER, SYN_C_LUT, SYN_C_FF, SYN_C_BRAM, SYN_C_DSP } SynCellClass;

static int syn_has(const char *s, const char *needle)
{
    for (; *s; s++)
        if (syn_istarts(s, needle))
            return 1;
    return 0;
}

static SynCellClass syn_classify(const char *cell)
{
    if (syn_has(cell, "LUT"))
        return SYN_C_LUT;
    if (syn_has(cell, "RAM") || syn_has(cell, "DP16KD") || syn_has(cell, "DP8KC") || syn_has(cell, "SPRAM") ||
        syn_has(cell, "BSRAM") || syn_has(cell, "$mem") || syn_has(cell, "M10K") || syn_has(cell, "M9K") ||
        syn_has(cell, "M20K") || syn_has(cell, "_SDP") || syn_has(cell, "SDPB") || syn_has(cell, "DPB"))
        return SYN_C_BRAM;
    if (syn_has(cell, "DSP") || syn_has(cell, "MAC16") || syn_has(cell, "MULT") || syn_has(cell, "ALU54") ||
        syn_has(cell, "$mul") || syn_has(cell, "$macc"))
        return SYN_C_DSP;
    if (syn_has(cell, "DFF") || syn_has(cell, "FF") || syn_has(cell, "$dff") || syn_has(cell, "$sdff") ||
        syn_has(cell, "$adff") || syn_has(cell, "$_SDFF") || syn_has(cell, "$_DLATCH") || syn_has(cell, "LATCH") ||
        (cell[0] == 'F' && cell[1] == 'D' && (cell[2] == 'R' || cell[2] == 'S' || cell[2] == 'C' || cell[2] == 'P' ||
                                              cell[2] == 'E' || cell[2] == 0)))
        return SYN_C_FF;
    return SYN_C_OTHER;
}

static void syn_add(int64_t *slot, int64_t v)
{
    *slot = (*slot < 0 ? 0 : *slot) + v;
}

/* one cell line: "     SB_LUT4      28" (old) or "      28   SB_LUT4" (Yosys >= 0.40); the
 * cell name is returned in name (NUL-terminated) */
static int syn_cell_line(const char *line, char *name, size_t cap, int64_t *count)
{
    const char *p = syn_skip_ws(line), *q;
    size_t n;
    int64_t v;
    if (tern_is_digit((unsigned char)*p)) {
        if (!syn_int(p, &v, &q))
            return 0;
        q = syn_skip_ws(q);
        if (!(*q == '$' || *q == '\\' || tern_is_alpha((unsigned char)*q) || *q == '_'))
            return 0;
        p = q;
        while (*q && !tern_is_space((unsigned char)*q))
            q++;
        if (*syn_skip_ws(q) && *syn_skip_ws(q) != '\n' && *syn_skip_ws(q) != '\r')
            return 0; /* more words: a summary line ("48 cells" is filtered by the caller) */
    } else if (*p == '$' || *p == '\\' || tern_is_alpha((unsigned char)*p) || *p == '_') {
        q = p;
        while (*q && !tern_is_space((unsigned char)*q))
            q++;
        if (!syn_int(q, &v, NULL))
            return 0;
        {
            const char *r = syn_skip_ws(q);
            while (tern_is_digit((unsigned char)*r) || *r == ',')
                r++;
            r = syn_skip_ws(r);
            if (*r && *r != '\n' && *r != '\r')
                return 0;
        }
    } else {
        return 0;
    }
    n = (size_t)(q - p);
    if (*p == '\\') {
        p++;
        n--;
    }
    if (n >= cap)
        n = cap - 1;
    memcpy(name, p, n);
    name[n] = 0;
    *count = v;
    return 1;
}

int syn_parse_yosys_stat(const char *text, SynReport *r)
{
    /* use the last section: the design-hierarchy totals, or the (flattened) top */
    const char *sec = text, *p, *q;
    int found = 0;
    for (p = text; (p = strstr(p, "=== ")) != NULL; p += 4)
        sec = p;
    for (p = sec; *p;) {
        const char *e = strchr(p, '\n');
        size_t n = e ? (size_t)(e - p) : strlen(p);
        char *line = xstrndup(p, n), name[128];
        int64_t v;
        if ((q = strstr(line, "Number of cells:")) != NULL) {
            if (syn_int(q + 16, &v, NULL)) {
                r->cells = v;
                found++;
            }
        } else if ((q = strstr(line, " cells")) != NULL && syn_int(line, &v, NULL) &&
                   *syn_skip_ws(q + 6) == 0) {
            r->cells = v;
            found++;
        } else if (!strstr(line, "Number of") && !strstr(line, "wire") && !strstr(line, "memor") &&
                   !strstr(line, "process") && !strstr(line, "cells") && !strstr(line, "port") &&
                   !strstr(line, "Chip area") && syn_cell_line(line, name, sizeof name, &v)) {
            switch (syn_classify(name)) {
            case SYN_C_LUT: syn_add(&r->luts, v); found++; break;
            case SYN_C_FF: syn_add(&r->ffs, v); found++; break;
            case SYN_C_BRAM: syn_add(&r->brams, v); found++; break;
            case SYN_C_DSP: syn_add(&r->dsps, v); found++; break;
            case SYN_C_OTHER: break;
            }
        }
        free(line);
        p = e ? e + 1 : p + n;
    }
    if (found) {
        /* a section without e.g. RAM cells has none of them (LUTs stay
         * unknown for gate-level flows: the cell count stands in) */
        if (r->ffs < 0)
            r->ffs = 0;
        if (r->brams < 0)
            r->brams = 0;
        if (r->dsps < 0)
            r->dsps = 0;
    }
    return found;
}

int syn_parse_nextpnr(const char *text, SynReport *r)
{
    /* "Max frequency for clock 'clk': 123.45 MHz (PASS at 100.00 MHz)"; nextpnr prints an
     * estimate after placement and the final figure after routing: the last line per clock
     * counts, and the slowest clock is reported */
    const char *p = text;
    char names[16][96];
    double fmax[16], target[16];
    size_t n = 0, i;
    int found = 0;
    while ((p = strstr(p, "Max frequency for clock")) != NULL) {
        const char *q = strchr(p, '\'');
        const char *c = q ? strstr(q + 1, "': ") : NULL;
        double f, t = 0;
        const char *e;
        p += 23;
        if (!q || !c || !syn_num(c + 3, &f, &e))
            continue;
        if ((e = strstr(e, " at ")) != NULL)
            syn_num(e + 4, &t, NULL);
        for (i = 0; i < n; i++)
            if ((size_t)(c - q - 1) < sizeof names[i] && strncmp(names[i], q + 1, (size_t)(c - q - 1)) == 0 &&
                names[i][c - q - 1] == 0)
                break;
        if (i == n) {
            if (n == 16)
                continue;
            snprintf(names[n], sizeof names[n], "%.*s", (int)(c - q - 1), q + 1);
            n++;
        }
        fmax[i] = f;
        target[i] = t;
        found++;
    }
    for (i = 0; i < n; i++)
        if (r->fmax_mhz < 0 || fmax[i] < r->fmax_mhz) {
            r->fmax_mhz = fmax[i];
            if (target[i] > 0) {
                r->period_ns = 1000.0 / target[i];
                r->wns_ns = r->period_ns - 1000.0 / fmax[i];
                r->has_wns = 1;
            }
        }
    return found;
}

/* Vivado table row: "| Slice LUTs*   |  123 |     0 |  20800 |  0.59 |" */
static int syn_table_row(const char *text, const char *label, int64_t *out)
{
    const char *p = text;
    size_t ll = strlen(label);
    while ((p = strstr(p, label)) != NULL) {
        const char *b = p, *q = p + ll;
        int64_t v;
        while (b > text && (b[-1] == ' ' || b[-1] == '\t'))
            b--;
        if (b == text || b[-1] != '|') {
            p += ll;
            continue;
        }
        while (*q == '*' || *q == ' ' || *q == '\t')
            q++;
        if (*q == '|' && syn_int(q + 1, &v, NULL)) {
            *out = v;
            return 1;
        }
        p += ll;
    }
    return 0;
}

int syn_parse_vivado_util(const char *text, SynReport *r)
{
    int found = 0;
    int64_t v;
    double d;
    if (syn_table_row(text, "Slice LUTs", &v) || syn_table_row(text, "CLB LUTs", &v)) {
        r->luts = v;
        found++;
    }
    if (syn_table_row(text, "Slice Registers", &v) || syn_table_row(text, "CLB Registers", &v) ||
        syn_table_row(text, "Register as Flip Flop", &v)) {
        r->ffs = v;
        found++;
    }
    /* Block RAM Tile can be fractional ("| Block RAM Tile | 1.5 |") */
    {
        const char *p = strstr(text, "| Block RAM Tile");
        if (p) {
            const char *q = strchr(p + 2, '|');
            if (q && syn_num(q + 1, &d, NULL)) {
                r->brams = (int64_t)(d + 0.999);
                found++;
            }
        }
    }
    if (syn_table_row(text, "DSPs", &v)) {
        r->dsps = v;
        found++;
    }
    return found;
}

/* the row of numbers under a header line containing `col` (separated by a
 * dashed line); returns the value in that column */
static int syn_header_value(const char *text, const char *header_key, const char *col, double *out)
{
    const char *h = strstr(text, header_key), *ls, *le, *rowp;
    int idx = -1, k = 0;
    const char *p;
    if (!h)
        return 0;
    ls = h;
    while (ls > text && ls[-1] != '\n')
        ls--;
    le = strchr(h, '\n');
    if (!le)
        return 0;
    /* column index of `col` among whitespace-separated words */
    for (p = ls; p < le;) {
        const char *w;
        while (p < le && (*p == ' ' || *p == '\t'))
            p++;
        if (p >= le)
            break;
        w = p;
        while (p < le && *p != ' ' && *p != '\t')
            p++;
        if ((size_t)(p - w) == strlen(col) && strncmp(w, col, (size_t)(p - w)) == 0) {
            idx = k;
            break;
        }
        k++;
    }
    if (idx < 0)
        return 0;
    /* skip the dashes line */
    rowp = le + 1;
    {
        const char *e2 = strchr(rowp, '\n');
        if (!e2)
            return 0;
        if (strstr(rowp, "---") && strstr(rowp, "---") < e2)
            rowp = e2 + 1;
    }
    for (k = 0, p = rowp; *p && *p != '\n'; k++) {
        double v;
        const char *e;
        while (*p == ' ' || *p == '\t')
            p++;
        if (k == idx)
            return syn_num(p, &v, &e) ? (*out = v, 1) : 0;
        while (*p && *p != ' ' && *p != '\t' && *p != '\n')
            p++;
    }
    return 0;
}

int syn_parse_vivado_timing(const char *text, SynReport *r)
{
    int found = 0;
    double wns, period;
    const char *ds = strstr(text, "Design Timing Summary");
    if (syn_header_value(ds ? ds : text, "WNS(ns)", "WNS(ns)", &wns)) {
        r->wns_ns = wns;
        r->has_wns = 1;
        found++;
    }
    {
        /* Clock Summary: "clk    {0.000 5.000}      10.000          100.000" (first clock) */
        const char *cs = strstr(text, "Clock Summary"), *h = cs ? strstr(cs, "Period(ns)") : NULL;
        if (h && (h = strchr(h, '\n')) != NULL && (h = strchr(h + 1, '\n')) != NULL) {
            const char *nl = strchr(h + 1, '\n'), *br = strchr(h + 1, '}');
            if (br && (!nl || br < nl) && syn_num(br + 1, &period, NULL) && period > 0) {
                r->period_ns = period;
                found++;
            }
        }
    }
    if (r->has_wns && r->period_ns > 0 && r->period_ns - r->wns_ns > 0)
        r->fmax_mhz = 1000.0 / (r->period_ns - r->wns_ns);
    return found;
}

/* "Total registers : 64" -> 64 (first number after the colon) */
static int syn_colon_value(const char *text, const char *key, int64_t *out)
{
    const char *p = strstr(text, key);
    if (!p)
        return 0;
    p = strchr(p, ':');
    if (!p)
        return 0;
    return syn_int(p + 1, out, NULL);
}

int syn_parse_quartus_fit(const char *text, SynReport *r)
{
    int found = 0;
    int64_t v;
    if (syn_colon_value(text, "Logic utilization (in ALMs)", &v) || syn_colon_value(text, "Total logic elements", &v) ||
        syn_colon_value(text, "Logic utilization (ALMs needed", &v)) {
        r->luts = v;
        found++;
    }
    if (syn_colon_value(text, "Total registers", &v) || syn_colon_value(text, "Dedicated logic registers", &v)) {
        r->ffs = v;
        found++;
    }
    if (syn_colon_value(text, "Total RAM Blocks", &v) || syn_colon_value(text, "Total block memory bits", &v) ||
        syn_colon_value(text, "Total memory bits", &v)) {
        /* bits when no block count is reported */
        r->brams = v;
        found++;
    }
    if (syn_colon_value(text, "Total DSP Blocks", &v) ||
        syn_colon_value(text, "Embedded Multiplier 9-bit elements", &v) ||
        syn_colon_value(text, "Total DSP Blocks", &v)) {
        r->dsps = v;
        found++;
    }
    return found;
}

int syn_parse_quartus_sta(const char *text, SynReport *r)
{
    /* .sta.summary: "Type  : Slow 1100mV 85C Model Setup 'clk'\nSlack : 5.123" — the worst setup
     * slack; .sta.rpt: "; 163.43 MHz ; 163.43 MHz ; clk ;" (Fmax Summary) */
    const char *p = text;
    int found = 0;
    while ((p = strstr(p, "Setup '")) != NULL) {
        const char *s = strstr(p, "Slack");
        double v;
        if (s && (s = strchr(s, ':')) != NULL && syn_num(s + 1, &v, NULL)) {
            if (!r->has_wns || v < r->wns_ns)
                r->wns_ns = v;
            r->has_wns = 1;
            found++;
        }
        p += 7;
    }
    p = strstr(text, "Fmax Summary");
    if (p) {
        const char *q = p;
        while ((q = strstr(q, " MHz ;")) != NULL) {
            const char *b = q;
            double v;
            while (b > p && b[-1] != ';')
                b--;
            if (syn_num(b, &v, NULL) && v > 0) {
                if (r->fmax_mhz < 0 || v < r->fmax_mhz)
                    r->fmax_mhz = v;
                found++;
            }
            /* skip the restricted-Fmax column of the same row */
            q = strchr(q + 6, '\n');
            if (!q)
                break;
        }
    }
    return found;
}

static void syn_count(StrBuf *out, const char *label, int64_t v)
{
    if (v >= 0)
        sb_printf(out, "  %-6s %lld\n", label, (long long)v);
    else
        sb_printf(out, "  %-6s -\n", label);
}

void syn_report_print(const SynReport *r, double target_mhz, StrBuf *out)
{
    syn_count(out, "LUTs", r->luts);
    syn_count(out, "FFs", r->ffs);
    syn_count(out, "BRAM", r->brams);
    syn_count(out, "DSP", r->dsps);
    if (r->luts < 0 && r->cells >= 0)
        syn_count(out, "cells", r->cells);
    if (r->fmax_mhz > 0) {
        sb_printf(out, "  %-6s %.1f MHz", "Fmax", r->fmax_mhz);
        if (target_mhz > 0)
            sb_printf(out, " (target %.1f MHz%s)", target_mhz, r->fmax_mhz >= target_mhz ? ", met" : ", NOT MET");
        if (r->has_wns)
            sb_printf(out, ", WNS %.3f ns", r->wns_ns);
        sb_putc(out, '\n');
    } else if (r->has_wns) {
        sb_printf(out, "  %-6s %.3f ns%s\n", "WNS", r->wns_ns, r->wns_ns >= 0 ? " (met)" : " (NOT MET)");
    } else {
        sb_printf(out, "  %-6s - (no timing analysis for this flow)\n", "Fmax");
    }
}

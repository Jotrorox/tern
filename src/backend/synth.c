/* synth.c — `tern synth` (spec §13.2): build, then drive Yosys, Vivado or
 * Quartus with a generated script and summarize utilization and timing.
 *
 *     tern synth [--target <t>] [--tool yosys|vivado|quartus] [--top <m>]
 *                [--features <l>] [--no-run] [--keep] [<files>...]
 *
 * Files in build/<target>/synth/:
 *   synth.ys            Yosys: read_verilog of a Verilog-2005 emission of the
 *                       same IR (written next to the script; what Yosys reads
 *                       best), synth_ice40 / synth_ecp5 / synth_xilinx /
 *                       synth_gowin / synth by device family, `stat`;
 *                       nextpnr (ice40 / ecp5) for Fmax when it is installed
 *   synth.tcl           Vivado non-project mode: read_verilog -sv, read_xdc,
 *                       synth_design, opt/place/route, utilization and
 *                       timing-summary reports
 *   synth_quartus.tcl   Quartus: project_new, sources, SDC, execute_flow
 * The command is in cmd_synth.c; the report parsers (syn_parse_*) are
 * tested on canned reports in tests/fixtures/synth/. */

/* vlharness.c — tb_main.cpp, the generic C++ harness of the Verilator
 * backend (vlsim.c, `tern test --backend verilator`): it drives a model
 * through VPI over a line protocol on stdin/stdout (src/sim/remote.c), so
 * no per-design C++ is generated.  Golden copy:
 * tests/fixtures/verilator/tb_main.cpp. */
#include "../base/common.h"
#include "../base/str.h"
#include "backend.h"

/* ------------------------------------------------------------ harness -- */

static const char *const vls_harness_lines[] = {
    "// tb_main.cpp: generic Verilator harness of `tern test --backend verilator`,",
    "// generated by tern. Do not edit.",
    "//",
    "// The model is driven over stdin/stdout, one request per line; every",
    "// response line starts with '@' (other output, e.g. from $display, is",
    "// passed through and ignored by tern):",
    "//   C <i> <half_ps> <falling> <path>  declare top clock i      -> (none)",
    "//   R <active_low> <path>             declare a top reset      -> (none)",
    "//   I                                 initial evaluation       -> @ok",
    "//   P <path> <hex>                    drive a signal           -> @ok | @err <msg>",
    "//   G <path>                          read a signal            -> @v <hex> | @err <msg>",
    "//   M <path> <addr>                   read a memory word       -> @v <hex> | @err <msg>",
    "//   E                                 evaluate (settle)        -> @ok",
    "//   S <i> <n>                         n cycles of clock i      -> @ok",
    "//   N <ns>                            run every clock for ns   -> @ok",
    "//   X <i>...                          resets asserted, 2 cycles of each",
    "//                                     clock i, released        -> @ok",
    "//   D <path>                          VCD waves to path        -> @ok | @err <msg>",
    "//   Q                                 quit                     -> @bye",
    "// Signals are found with VPI (vpi_handle_by_name), values are hex strings.",
    "// After a failed assertion or $finish/$stop the model answers @stop.",
    "#include \"Vdut.h\"",
    "#include \"verilated.h\"",
    "#include \"verilated_vpi.h\"",
    "#if VM_TRACE",
    "#include \"verilated_vcd_c.h\"",
    "#endif",
    "#include <cstdio>",
    "#include <cstdlib>",
    "#include <cstring>",
    "#include <map>",
    "#include <string>",
    "#include <vector>",
    "",
    "namespace {",
    "",
    "struct Clock {",
    "    vpiHandle h;",
    "    unsigned long long half;",
    "    int falling;",
    "    int level;",
    "    unsigned long long next;",
    "};",
    "",
    "struct Reset {",
    "    vpiHandle h;",
    "    int low;",
    "};",
    "",
    "VerilatedContext *ctx;",
    "Vdut *top;",
    "std::vector<Clock> clocks;",
    "std::vector<std::string> clock_paths;",
    "std::vector<Reset> resets;",
    "std::vector<std::string> reset_paths;",
    "std::map<std::string, vpiHandle> handles;",
    "unsigned long long now_ps;",
    "bool stopped;",
    "#if VM_TRACE",
    "VerilatedVcdC *tfp;",
    "#endif",
    "",
    "vpiHandle find(const std::string &path)",
    "{",
    "    std::map<std::string, vpiHandle>::iterator it = handles.find(path);",
    "    if (it != handles.end())",
    "        return it->second;",
    "    vpiHandle h = vpi_handle_by_name(const_cast<PLI_BYTE8 *>(path.c_str()), NULL);",
    "    if (h)",
    "        handles[path] = h;",
    "    return h;",
    "}",
    "",
    "void eval_dump()",
    "{",
    "    ctx->time(now_ps);",
    "    top->eval();",
    "#if VM_TRACE",
    "    if (tfp)",
    "        tfp->dump(now_ps);",
    "#endif",
    "    if (ctx->gotFinish())",
    "        stopped = true;",
    "}",
    "",
    "void put_bit(vpiHandle h, int v)",
    "{",
    "    s_vpi_value val;",
    "    val.format = vpiIntVal;",
    "    val.value.integer = v;",
    "    vpi_put_value(h, &val, NULL, vpiNoDelay);",
    "}",
    "",
    "void toggle(Clock &c)",
    "{",
    "    c.level = !c.level;",
    "    put_bit(c.h, c.level);",
    "}",
    "",
    "void step(size_t ci, unsigned long long n)",
    "{",
    "    for (unsigned long long k = 0; k < n && !stopped; k++)",
    "        for (int e = 0; e < 2 && !stopped; e++) {",
    "            Clock &c = clocks[ci];",
    "            now_ps += c.half;",
    "            toggle(c);",
    "            eval_dump();",
    "            c.next = now_ps + c.half;",
    "        }",
    "}",
    "",
    "void run_ns(unsigned long long ns)",
    "{",
    "    unsigned long long target = now_ps + ns * 1000ull;",
    "    while (!stopped && !clocks.empty()) {",
    "        unsigned long long t = ~0ull;",
    "        for (size_t i = 0; i < clocks.size(); i++) {",
    "            unsigned long long nt = clocks[i].next > now_ps ? clocks[i].next : now_ps;",
    "            if (nt < t)",
    "                t = nt;",
    "        }",
    "        if (t > target)",
    "            break;",
    "        now_ps = t;",
    "        std::vector<size_t> due;",
    "        for (size_t i = 0; i < clocks.size(); i++)",
    "            if ((clocks[i].next > now_ps ? clocks[i].next : now_ps) == t)",
    "                due.push_back(i);",
    "        for (size_t i = 0; i < due.size(); i++)",
    "            toggle(clocks[due[i]]);",
    "        eval_dump();",
    "        for (size_t i = 0; i < due.size(); i++)",
    "            clocks[due[i]].next = t + clocks[due[i]].half;",
    "    }",
    "    now_ps = target;",
    "}",
    "",
    "bool read_line(std::string &line)",
    "{",
    "    int c;",
    "    line.clear();",
    "    while ((c = std::getchar()) != EOF && c != '\\n')",
    "        if (c != '\\r')",
    "            line += (char)c;",
    "    return c != EOF || !line.empty();",
    "}",
    "",
    "std::vector<std::string> split(const std::string &s)",
    "{",
    "    std::vector<std::string> out;",
    "    size_t i = 0;",
    "    while (i < s.size()) {",
    "        while (i < s.size() && s[i] == ' ')",
    "            i++;",
    "        size_t j = i;",
    "        while (j < s.size() && s[j] != ' ')",
    "            j++;",
    "        if (j > i)",
    "            out.push_back(s.substr(i, j - i));",
    "        i = j;",
    "    }",
    "    return out;",
    "}",
    "",
    "void reply(const char *fmt, const char *arg)",
    "{",
    "    std::printf(fmt, arg);",
    "    std::fflush(stdout);",
    "}",
    "",
    "void read_value(vpiHandle h)",
    "{",
    "    s_vpi_value v;",
    "    v.format = vpiHexStrVal;",
    "    vpi_get_value(h, &v);",
    "    reply(\"@v %s\\n\", v.value.str ? v.value.str : \"0\");",
    "}",
    "",
    "}  // namespace",
    "",
    "int main(int argc, char **argv)",
    "{",
    "    std::string line;",
    "    ctx = new VerilatedContext;",
    "    ctx->commandArgs(argc, argv);",
    "    ctx->fatalOnError(false);",
    "#if VM_TRACE",
    "    ctx->traceEverOn(true);",
    "#endif",
    "    top = new Vdut(ctx);",
    "    while (read_line(line)) {",
    "        std::vector<std::string> a = split(line);",
    "        if (a.empty())",
    "            continue;",
    "        const std::string &op = a[0];",
    "        if (op == \"Q\") {",
    "            reply(\"@bye%s\\n\", \"\");",
    "            break;",
    "        }",
    "        if (stopped && op != \"C\" && op != \"R\") {",
    "            reply(\"@stop%s\\n\", \"\");",
    "            continue;",
    "        }",
    "        if (op == \"C\" && a.size() == 5) {",
    "            size_t i = std::strtoul(a[1].c_str(), NULL, 10);",
    "            if (clocks.size() <= i) {",
    "                clocks.resize(i + 1);",
    "                clock_paths.resize(i + 1);",
    "            }",
    "            clocks[i].h = NULL;",
    "            clocks[i].half = std::strtoull(a[2].c_str(), NULL, 10);",
    "            clocks[i].falling = std::atoi(a[3].c_str());",
    "            clocks[i].level = clocks[i].falling ? 1 : 0;",
    "            clocks[i].next = clocks[i].half;",
    "            clock_paths[i] = a[4];",
    "        } else if (op == \"R\" && a.size() == 3) {",
    "            Reset r;",
    "            r.h = NULL;",
    "            r.low = std::atoi(a[1].c_str());",
    "            resets.push_back(r);",
    "            reset_paths.push_back(a[2]);",
    "        } else if (op == \"I\") {",
    "            top->eval();",
    "            std::string missing;",
    "            for (size_t i = 0; i < clocks.size(); i++) {",
    "                clocks[i].h = find(clock_paths[i]);",
    "                if (!clocks[i].h)",
    "                    missing = clock_paths[i];",
    "                else",
    "                    put_bit(clocks[i].h, clocks[i].level);",
    "            }",
    "            for (size_t i = 0; i < resets.size(); i++) {",
    "                resets[i].h = find(reset_paths[i]);",
    "                if (!resets[i].h)",
    "                    missing = reset_paths[i];",
    "            }",
    "            if (!missing.empty()) {",
    "                reply(\"@err no signal %s\\n\", missing.c_str());",
    "                continue;",
    "            }",
    "            eval_dump();",
    "            reply(\"@ok%s\\n\", \"\");",
    "        } else if (op == \"P\" && a.size() == 3) {",
    "            vpiHandle h = find(a[1]);",
    "            if (!h) {",
    "                reply(\"@err no signal %s\\n\", a[1].c_str());",
    "                continue;",
    "            }",
    "            s_vpi_value v;",
    "            v.format = vpiHexStrVal;",
    "            v.value.str = const_cast<PLI_BYTE8 *>(a[2].c_str());",
    "            vpi_put_value(h, &v, NULL, vpiNoDelay);",
    "            reply(\"@ok%s\\n\", \"\");",
    "        } else if (op == \"G\" && a.size() == 2) {",
    "            vpiHandle h = find(a[1]);",
    "            if (!h) {",
    "                reply(\"@err no signal %s\\n\", a[1].c_str());",
    "                continue;",
    "            }",
    "            read_value(h);",
    "        } else if (op == \"M\" && a.size() == 3) {",
    "            vpiHandle h = find(a[1]);",
    "            vpiHandle w = h ? vpi_handle_by_index(h, (PLI_INT32)std::strtol(a[2].c_str(), NULL, 10)) : NULL;",
    "            if (!w) {",
    "                reply(\"@err no memory word %s\\n\", line.c_str());",
    "                continue;",
    "            }",
    "            read_value(w);",
    "        } else if (op == \"E\") {",
    "            eval_dump();",
    "            reply(stopped ? \"@stop%s\\n\" : \"@ok%s\\n\", \"\");",
    "        } else if (op == \"S\" && a.size() == 3) {",
    "            size_t i = std::strtoul(a[1].c_str(), NULL, 10);",
    "            if (i < clocks.size())",
    "                step(i, std::strtoull(a[2].c_str(), NULL, 10));",
    "            reply(stopped ? \"@stop%s\\n\" : \"@ok%s\\n\", \"\");",
    "        } else if (op == \"N\" && a.size() == 2) {",
    "            run_ns(std::strtoull(a[1].c_str(), NULL, 10));",
    "            reply(stopped ? \"@stop%s\\n\" : \"@ok%s\\n\", \"\");",
    "        } else if (op == \"X\") {",
    "            for (size_t i = 0; i < resets.size(); i++)",
    "                put_bit(resets[i].h, resets[i].low ? 0 : 1);",
    "            eval_dump();",
    "            for (size_t k = 1; k < a.size(); k++) {",
    "                size_t i = std::strtoul(a[k].c_str(), NULL, 10);",
    "                if (i < clocks.size())",
    "                    step(i, 2);",
    "            }",
    "            for (size_t i = 0; i < resets.size(); i++)",
    "                put_bit(resets[i].h, resets[i].low ? 1 : 0);",
    "            eval_dump();",
    "            reply(stopped ? \"@stop%s\\n\" : \"@ok%s\\n\", \"\");",
    "        } else if (op == \"D\" && a.size() == 2) {",
    "#if VM_TRACE",
    "            if (tfp) {",
    "                tfp->close();",
    "            } else {",
    "                tfp = new VerilatedVcdC;",
    "                top->trace(tfp, 99);",
    "            }",
    "            tfp->open(a[1].c_str());",
    "            tfp->dump(now_ps);",
    "            reply(\"@ok%s\\n\", \"\");",
    "#else",
    "            reply(\"@err %s\\n\", \"the model was built without --trace\");",
    "#endif",
    "        } else {",
    "            reply(\"@err bad request: %s\\n\", line.c_str());",
    "        }",
    "    }",
    "#if VM_TRACE",
    "    if (tfp)",
    "        tfp->close();",
    "#endif",
    "    top->final();",
    "    delete top;",
    "    delete ctx;",
    "    return 0;",
    "}",
};

const char *vls_harness_source(void)
{
    static char *text;
    if (!text) {
        StrBuf sb = {0};
        size_t i;
        for (i = 0; i < TERN_ARRAY_LEN(vls_harness_lines); i++)
            sb_printf(&sb, "%s\n", vls_harness_lines[i]);
        text = sb_take(&sb);
    }
    return text;
}


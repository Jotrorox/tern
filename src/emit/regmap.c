/* regmap.c — register-map outputs (spec §10.3): a C header <Map>.h with
 * offsets, field shifts/masks and accessors, a CMSIS-SVD description
 * <Map>.svd and a Markdown table <Map>.md for the documentation. */
#include "emit.h"
#include "../base/str.h"

/* "DmaCtrl" -> "DMA_CTRL", "rx_fifo" -> "RX_FIFO" (upper = 1) or the
 * lower-case snake form (upper = 0). */
static void rmap_snake(const char *s, int upper, StrBuf *out)
{
    size_t i;
    for (i = 0; s && s[i]; i++) {
        int c = (unsigned char)s[i];
        if (!tern_is_alnum(c))
            c = '_';
        if (i && tern_is_upper(c) && (tern_is_lower((unsigned char)s[i - 1]) || tern_is_digit((unsigned char)s[i - 1])))
            sb_putc(out, '_');
        sb_putc(out, upper ? tern_to_upper(c) : tern_to_lower(c));
    }
}

static const char *rmap_access_svd(IrAccess a)
{
    switch (a) {
    case IR_RO: return "read-only";
    case IR_WO: return "write-only";
    default: return "read-write";
    }
}

static const char *rmap_access_text(IrAccess a)
{
    switch (a) {
    case IR_RW: return "read/write";
    case IR_RO: return "read-only";
    case IR_WO: return "write-only";
    case IR_W1C: return "read, write 1 to clear";
    case IR_RW1S: return "read, write 1 to set";
    }
    return "?";
}

static uint32_t rmap_ctype_bits(uint32_t w)
{
    return w <= 8 ? 8 : w <= 16 ? 16 : w <= 32 ? 32 : w <= 64 ? 64 : 0;
}

static void rmap_hex(StrBuf *out, uint64_t v, uint32_t bits)
{
    uint32_t nd = bits ? (bits + 3) / 4 : 1;
    sb_printf(out, "0x%0*llx", (int)nd, (unsigned long long)v);
}

static uint64_t rmap_mask(uint32_t lo, uint32_t w)
{
    uint64_t m = w >= 64 ? ~UINT64_C(0) : (UINT64_C(1) << w) - 1u;
    return lo >= 64 ? 0 : m << lo;
}

static void rmap_type(const IrType *t, StrBuf *out)
{
    if (!t) {
        sb_puts(out, "-");
        return;
    }
    ir_type_print(t, out);
}

/* one-line doc text: the first paragraph, its lines joined with spaces */
static void rmap_doc_para(const char *doc, StrBuf *out)
{
    size_t i = 0;
    if (!doc)
        return;
    while (doc[i] == ' ' || doc[i] == '\t')
        i++;
    for (; doc[i]; i++) {
        if (doc[i] == '\n') {
            size_t j = i + 1;
            while (doc[j] == ' ' || doc[j] == '\t')
                j++;
            if (!doc[j] || doc[j] == '\n')
                break; /* blank line: end of the paragraph */
            sb_putc(out, ' ');
            i = j - 1;
            continue;
        }
        sb_putc(out, doc[i]);
    }
}

static void rmap_doc_line(const char *doc, StrBuf *out)
{
    StrBuf p = {0};
    size_t i;
    rmap_doc_para(doc, &p);
    for (i = 0; i < p.len; i++)
        sb_putc(out, p.data[i] == '*' && p.data[i + 1] == '/' ? '-' : p.data[i]);
    sb_free(&p);
}

/* -------------------------------------------------------------- header -- */

void rmap_emit_header(const IrRegmap *r, StrBuf *out)
{
    StrBuf mp = {0}, ml = {0}, guard = {0};
    uint32_t i, j, k;
    rmap_snake(r->name, 1, &mp);
    rmap_snake(r->name, 0, &ml);
    sb_printf(&guard, "%s_H", sb_cstr(&mp));
    sb_printf(out, "/* %s.h: register map %s", r->name, r->name);
    if (r->package)
        sb_printf(out, " (%s)", r->package);
    sb_puts(out, ", generated by tern. Do not edit.\n");
    sb_puts(out, " *\n"
                 " * <MAP>_<REG>_OFFSET          byte offset of a register in the block\n"
                 " * <MAP>_<REG>_<FIELD>_SHIFT   bit position of a field\n"
                 " * <MAP>_<REG>_<FIELD>_MASK    field bits in the register word\n"
                 " * <MAP>_<REG>_<FIELD>_GET(v)  field value of register word v\n"
                 " * <MAP>_<REG>_<FIELD>_SET(v, x)  v with the field replaced by x\n"
                 " * <map>_read_<reg>(base) / <map>_write_<reg>(base, v)  volatile accesses\n"
                 " */\n");
    sb_printf(out, "#ifndef %s\n#define %s\n\n#include <stdint.h>\n", sb_cstr(&guard), sb_cstr(&guard));
    for (i = 0; i < r->nregs; i++) {
        const IrReg *g = &r->regs[i];
        StrBuf rp = {0}, rl = {0};
        uint32_t cb = rmap_ctype_bits(g->width);
        const char *suf = cb == 64 ? "ull" : "u";
        rmap_snake(g->name, 1, &rp);
        rmap_snake(g->name, 0, &rl);
        sb_printf(out, "\n/* %s: %s, %u bits", g->name, rmap_access_text(g->access), g->width);
        if (g->is_stream)
            sb_puts(out, g->access == IR_RO ? ", FIFO: each read pops" : ", FIFO: each write pushes");
        if (g->doc) {
            sb_puts(out, ". ");
            rmap_doc_line(g->doc, out);
        }
        sb_puts(out, " */\n");
        sb_printf(out, "#define %s_%s_OFFSET 0x%02llxu\n", sb_cstr(&mp), sb_cstr(&rp), (unsigned long long)g->offset);
        for (j = 0; j < g->nfields; j++) {
            const IrRegField *f = &g->fields[j];
            StrBuf fp = {0}, nm = {0};
            rmap_snake(f->name, 1, &fp);
            sb_printf(&nm, "%s_%s_%s", sb_cstr(&mp), sb_cstr(&rp), sb_cstr(&fp));
            sb_printf(out, "#define %s_SHIFT %uu\n", sb_cstr(&nm), f->lo);
            sb_printf(out, "#define %s_WIDTH %uu\n", sb_cstr(&nm), f->width);
            if (cb) {
                sb_printf(out, "#define %s_MASK ", sb_cstr(&nm));
                rmap_hex(out, rmap_mask(f->lo, f->width), cb);
                sb_printf(out, "%s\n", suf);
                sb_printf(out, "#define %s_GET(v) (((v) & %s_MASK) >> %s_SHIFT)\n", sb_cstr(&nm), sb_cstr(&nm),
                          sb_cstr(&nm));
                sb_printf(out,
                          "#define %s_SET(v, x) (((v) & ~%s_MASK) | (((uint%u_t)(x) << %s_SHIFT) & %s_MASK))\n",
                          sb_cstr(&nm), sb_cstr(&nm), cb, sb_cstr(&nm), sb_cstr(&nm));
            }
            if (f->type && f->type->kind == IRT_ENUM)
                for (k = 0; k < f->type->nvariants; k++) {
                    const IrVariant *v = &f->type->variants[k];
                    StrBuf vn = {0};
                    rmap_snake(v->name, 1, &vn);
                    sb_printf(out, "#define %s_%s %llu%s  /* %s::%s */\n", sb_cstr(&nm), sb_cstr(&vn),
                              (unsigned long long)ir_bits_low64(&v->tag), suf,
                              f->type->name ? f->type->name : "enum", v->name);
                    sb_free(&vn);
                }
            sb_free(&fp);
            sb_free(&nm);
        }
        if (cb) {
            if (g->access != IR_WO)
                sb_printf(out,
                          "static inline uint%u_t %s_read_%s(uintptr_t base)\n"
                          "{\n    return *(volatile const uint%u_t *)(base + %s_%s_OFFSET);\n}\n",
                          cb, sb_cstr(&ml), sb_cstr(&rl), cb, sb_cstr(&mp), sb_cstr(&rp));
            if (g->access != IR_RO)
                sb_printf(out,
                          "static inline void %s_write_%s(uintptr_t base, uint%u_t v)\n"
                          "{\n    *(volatile uint%u_t *)(base + %s_%s_OFFSET) = v;\n}\n",
                          sb_cstr(&ml), sb_cstr(&rl), cb, cb, sb_cstr(&mp), sb_cstr(&rp));
        } else {
            sb_printf(out, "/* %s is wider than 64 bits: access it in 32-bit words */\n", g->name);
        }
        sb_free(&rp);
        sb_free(&rl);
    }
    sb_printf(out, "\n#endif /* %s */\n", sb_cstr(&guard));
    sb_free(&mp);
    sb_free(&ml);
    sb_free(&guard);
}

/* ----------------------------------------------------------------- SVD -- */

static void rmap_xml(const char *s, StrBuf *out)
{
    for (; s && *s; s++) {
        switch (*s) {
        case '&': sb_puts(out, "&amp;"); break;
        case '<': sb_puts(out, "&lt;"); break;
        case '>': sb_puts(out, "&gt;"); break;
        case '"': sb_puts(out, "&quot;"); break;
        case '\n': sb_putc(out, ' '); break;
        default: sb_putc(out, *s); break;
        }
    }
}

static void rmap_svd_mwv(IrAccess a, int ind, StrBuf *out)
{
    if (a == IR_W1C || a == IR_RW1S) {
        sb_indent(out, ind);
        sb_printf(out, "<modifiedWriteValues>%s</modifiedWriteValues>\n", a == IR_W1C ? "oneToClear" : "oneToSet");
    }
}

void rmap_emit_svd(const IrRegmap *r, StrBuf *out)
{
    uint32_t i, j, k, maxw = 8;
    uint64_t size = 0;
    for (i = 0; i < r->nregs; i++) {
        uint64_t end = r->regs[i].offset + (r->regs[i].width + 7) / 8;
        if (end > size)
            size = end;
        if (r->regs[i].width > maxw)
            maxw = r->regs[i].width;
    }
    if (maxw < 32)
        maxw = 32;
    sb_puts(out, "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    sb_printf(out, "<!-- %s.svd: register map %s, generated by tern. Do not edit. -->\n", r->name, r->name);
    sb_puts(out, "<device schemaVersion=\"1.3\" xmlns:xs=\"http://www.w3.org/2001/XMLSchema-instance\" "
                 "xs:noNamespaceSchemaLocation=\"CMSIS-SVD.xsd\">\n");
    sb_puts(out, "  <name>");
    rmap_xml(r->name, out);
    sb_puts(out, "</name>\n  <version>1.0</version>\n  <description>Register map ");
    rmap_xml(r->name, out);
    sb_puts(out, "</description>\n  <addressUnitBits>8</addressUnitBits>\n");
    sb_printf(out, "  <width>%u</width>\n", maxw);
    sb_puts(out, "  <peripherals>\n    <peripheral>\n      <name>");
    rmap_xml(r->name, out);
    sb_puts(out, "</name>\n      <description>");
    rmap_xml(r->name, out);
    if (r->package) {
        sb_puts(out, " (");
        rmap_xml(r->package, out);
        sb_putc(out, ')');
    }
    sb_puts(out, "</description>\n      <baseAddress>0x00000000</baseAddress>\n");
    sb_printf(out,
              "      <addressBlock>\n        <offset>0x0</offset>\n        <size>0x%llx</size>\n"
              "        <usage>registers</usage>\n      </addressBlock>\n",
              (unsigned long long)(size ? size : 4));
    sb_puts(out, "      <registers>\n");
    for (i = 0; i < r->nregs; i++) {
        const IrReg *g = &r->regs[i];
        sb_puts(out, "        <register>\n          <name>");
        rmap_xml(g->name, out);
        sb_puts(out, "</name>\n");
        sb_puts(out, "          <description>");
        if (g->doc) {
            StrBuf d = {0};
            rmap_doc_line(g->doc, &d);
            rmap_xml(sb_cstr(&d), out);
            sb_free(&d);
        } else {
            rmap_xml(g->name, out);
        }
        sb_puts(out, "</description>\n");
        sb_printf(out, "          <addressOffset>0x%llx</addressOffset>\n", (unsigned long long)g->offset);
        sb_printf(out, "          <size>%u</size>\n", g->width);
        sb_printf(out, "          <access>%s</access>\n", rmap_access_svd(g->access));
        rmap_svd_mwv(g->access, 10, out);
        if (g->is_stream && g->access != IR_WO)
            sb_puts(out, "          <readAction>modify</readAction>\n");
        if (g->nfields) {
            sb_puts(out, "          <fields>\n");
            for (j = 0; j < g->nfields; j++) {
                const IrRegField *f = &g->fields[j];
                sb_puts(out, "            <field>\n              <name>");
                rmap_xml(f->name, out);
                sb_puts(out, "</name>\n");
                sb_printf(out, "              <bitOffset>%u</bitOffset>\n              <bitWidth>%u</bitWidth>\n",
                          f->lo, f->width);
                sb_printf(out, "              <access>%s</access>\n", rmap_access_svd(g->access));
                rmap_svd_mwv(g->access, 14, out);
                if (f->type && f->type->kind == IRT_ENUM && f->type->nvariants) {
                    sb_puts(out, "              <enumeratedValues>\n");
                    if (f->type->name) {
                        sb_puts(out, "                <name>");
                        rmap_xml(f->type->name, out);
                        sb_puts(out, "</name>\n");
                    }
                    for (k = 0; k < f->type->nvariants; k++) {
                        const IrVariant *v = &f->type->variants[k];
                        sb_puts(out, "                <enumeratedValue>\n                  <name>");
                        rmap_xml(v->name, out);
                        sb_printf(out, "</name>\n                  <value>%llu</value>\n                </enumeratedValue>\n",
                                  (unsigned long long)ir_bits_low64(&v->tag));
                    }
                    sb_puts(out, "              </enumeratedValues>\n");
                }
                sb_puts(out, "            </field>\n");
            }
            sb_puts(out, "          </fields>\n");
        }
        sb_puts(out, "        </register>\n");
    }
    sb_puts(out, "      </registers>\n    </peripheral>\n  </peripherals>\n</device>\n");
}

/* ------------------------------------------------------------ Markdown -- */

static void rmap_md_text(const char *s, int cell, StrBuf *out)
{
    for (; s && *s && (!cell || *s != '\n'); s++) {
        if (*s == '|' && cell)
            sb_puts(out, "\\|");
        else if (*s == '<')
            sb_puts(out, "&lt;");
        else if (*s == '>')
            sb_puts(out, "&gt;");
        else if (*s == '&')
            sb_puts(out, "&amp;");
        else
            sb_putc(out, *s);
    }
}

static void rmap_md_cell(const char *s, StrBuf *out)
{
    StrBuf p = {0};
    rmap_doc_para(s, &p);
    rmap_md_text(sb_cstr(&p), 1, out);
    sb_free(&p);
}

void rmap_emit_markdown(const IrRegmap *r, StrBuf *out)
{
    uint32_t i, j, k;
    uint64_t maxoff = 0;
    int ow;
    for (i = 0; i < r->nregs; i++)
        if (r->regs[i].offset > maxoff)
            maxoff = r->regs[i].offset;
    ow = maxoff > 0xFFFF ? 8 : maxoff > 0xFF ? 4 : 2;
    sb_printf(out, "# Register map `%s`\n\n", r->name);
    sb_puts(out, "<!-- generated by tern; do not edit -->\n\n");
    if (r->package)
        sb_printf(out, "Package `%s`. ", r->package);
    sb_printf(out, "%u register%s; offsets are byte addresses relative to the block base.\n\n", r->nregs,
              r->nregs == 1 ? "" : "s");
    sb_puts(out, "| Offset | Register | Access | Width | Description |\n");
    sb_puts(out, "|-------:|----------|--------|------:|-------------|\n");
    for (i = 0; i < r->nregs; i++) {
        const IrReg *g = &r->regs[i];
        sb_printf(out, "| 0x%0*llx | `%s` | %s | %u | ", ow, (unsigned long long)g->offset, g->name,
                  ir_access_name(g->access), g->width);
        if (g->is_stream)
            sb_puts(out, g->access == IR_RO ? "FIFO (read pops)." : "FIFO (write pushes).");
        if (g->is_stream && g->doc)
            sb_putc(out, ' ');
        rmap_md_cell(g->doc, out);
        sb_puts(out, " |\n");
    }
    for (i = 0; i < r->nregs; i++) {
        const IrReg *g = &r->regs[i];
        sb_printf(out, "\n## `%s` (0x%0*llx, %s)\n\n", g->name, ow, (unsigned long long)g->offset,
                  rmap_access_text(g->access));
        if (g->doc) {
            rmap_md_text(g->doc, 0, out);
            sb_puts(out, "\n\n");
        }
        if (!g->nfields) {
            sb_printf(out, "Scalar register, bits %u:0.\n", g->width - 1);
            continue;
        }
        sb_puts(out, "| Bits | Field | Type | Values |\n");
        sb_puts(out, "|------|-------|------|--------|\n");
        for (j = 0; j < g->nfields; j++) {
            const IrRegField *f = &g->fields[j];
            StrBuf t = {0};
            if (f->width == 1)
                sb_printf(out, "| %u | `%s` | ", f->lo, f->name);
            else
                sb_printf(out, "| %u:%u | `%s` | ", f->lo + f->width - 1, f->lo, f->name);
            rmap_type(f->type, &t);
            rmap_md_cell(sb_cstr(&t), out);
            sb_puts(out, " | ");
            if (f->type && f->type->kind == IRT_ENUM)
                for (k = 0; k < f->type->nvariants; k++)
                    sb_printf(out, "%s%s = %llu", k ? ", " : "", f->type->variants[k].name,
                              (unsigned long long)ir_bits_low64(&f->type->variants[k].tag));
            sb_puts(out, " |\n");
            sb_free(&t);
        }
    }
}

/* -------------------------------------------------------------- driver -- */

int rmap_emit(const IrDesign *d, SvOutput *out)
{
    uint32_t i;
    for (i = 0; i < d->nregmaps; i++) {
        const IrRegmap *r = &d->regmaps[i];
        StrBuf sb = {0};
        char name[512];
        rmap_emit_header(r, &sb);
        snprintf(name, sizeof name, "%s.h", r->name);
        sv_output_add(out, name, SV_FILE_C_HEADER, &sb);
        rmap_emit_svd(r, &sb);
        snprintf(name, sizeof name, "%s.svd", r->name);
        sv_output_add(out, name, SV_FILE_SVD, &sb);
        rmap_emit_markdown(r, &sb);
        snprintf(name, sizeof name, "%s.md", r->name);
        sv_output_add(out, name, SV_FILE_MARKDOWN, &sb);
        sb_free(&sb);
    }
    return 0;
}
